export function getLevelInfo(stars: number) {
  let current = MUSICIAN_LEVELS[0];
  let next = MUSICIAN_LEVELS[1] ?? null;

  for (let i = 0; i < MUSICIAN_LEVELS.length; i++) {
    if (stars >= MUSICIAN_LEVELS[i].minStars) {
      current = MUSICIAN_LEVELS[i];
      next = MUSICIAN_LEVELS[i + 1] ?? null;
    }
  }

  return { current, next };
}

export function getNotesForDifficulty(clef: 'treble' | 'bass', difficulty: Difficulty): NoteDefinition[] {
  const pool = clef === 'treble' ? TREBLE_NOTES : BASS_NOTES;
  if (difficulty === 'principiante') {
    return pool.filter((n) => n.minDifficulty === 'principiante');
  }
  if (difficulty === 'esploratore') {
    return pool.filter((n) => n.minDifficulty === 'principiante' || n.minDifficulty === 'esploratore');
  }
  return pool;
}

export function getRhythmsForDifficulty(difficulty: Difficulty): RhythmDefinition[] {
  if (difficulty === 'principiante') {
    return RHYTHMS.filter((r) => r.minDifficulty === 'principiante');
  }
  if (difficulty === 'esploratore') {
    return RHYTHMS.filter((r) => r.minDifficulty === 'principiante' || r.minDifficulty === 'esploratore');
  }
  return RHYTHMS;
}

